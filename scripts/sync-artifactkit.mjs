#!/usr/bin/env node
/**
 * Copy artifactkit into the review console as a generated TypeScript module
 * (ADR-009 rule 3).
 *
 * The console runs on Lambda and Azure Functions, which have no home
 * directory, so it cannot read ~/.claude/skills/artifactkit at runtime. This
 * script embeds the files as strings instead. A styling change then arrives as
 * a visible commit rather than a silent runtime difference.
 *
 * Usage: pnpm sync:artifactkit
 * Source defaults to ~/.claude/skills/artifactkit/assets. Override with
 * ARTIFACTKIT_DIR.
 */
import { readFile, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import { createHash } from "node:crypto";

const source =
  process.env.ARTIFACTKIT_DIR ?? join(homedir(), ".claude", "skills", "artifactkit", "assets");
const target = new URL("../packages/api/src/web/artifactkit.generated.ts", import.meta.url);

const files = {
  THEME_CSS: "theme.css",
  COMPONENTS_CSS: "components.css",
  PRINT_CSS: "print.css",
  CORE_JS: "core.js",
};

const contents = {};
for (const [name, file] of Object.entries(files)) {
  try {
    contents[name] = await readFile(join(source, file), "utf8");
  } catch (error) {
    console.error(`cannot read ${join(source, file)}: ${error.message}`);
    console.error("Set ARTIFACTKIT_DIR to the folder holding theme.css, components.css, print.css and core.js.");
    process.exit(1);
  }
}

const digest = createHash("sha256")
  .update(Object.values(contents).join("\0"))
  .digest("hex")
  .slice(0, 12);

const header = `/**
 * GENERATED by scripts/sync-artifactkit.mjs. Do not edit by hand.
 *
 * The owner's artifactkit, embedded so the review console needs no file
 * access at runtime (ADR-009 rule 3). Re-run \`pnpm sync:artifactkit\` to pick
 * up changes, and commit the result.
 *
 * Source: ${source.replace(homedir(), "~")}
 * Synced: ${new Date().toISOString().slice(0, 10)}
 * Digest: ${digest}
 */
/* eslint-disable */
`;

const body = Object.entries(contents)
  .map(([name, text]) => `export const ${name}: string = ${JSON.stringify(text)};`)
  .join("\n\n");

await writeFile(
  target,
  `${header}\nexport const ARTIFACTKIT_DIGEST = ${JSON.stringify(digest)};\n\n${body}\n`,
);
console.log(`wrote ${target.pathname} (digest ${digest})`);
